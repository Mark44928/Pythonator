def rgb(value):
    return value

def color(value, text, bold=False, dim=False, italic=False):
    if not text:
        return ""
    r, g, b = value
    codes = []
    if bold:
        codes.append("1")
    if dim:
        codes.append("2")
    if italic:
        codes.append("3")
    codes.append(f"38;2;{r};{g};{b}")
    return f"\033[{';'.join(codes)}m{text}\033[0m"
